//! Start/stop feedback sounds (Handy `audio_feedback.rs`) and muting or lowering other audio while listening
//! ([`Duck`]), on a thread of their own, so the dictation state follower never waits for audio. Requests run one at a
//! time in the order sent: a duck sent after the start sound waits for it to finish (so it's heard), and a restore
//! never lands before its duck. Sounds play through the default output device.

use std::io::Cursor;
use std::sync::mpsc::{self, Sender, SyncSender};
use std::time::Duration;

use iris_core::audio::ducking::{Duck, DuckState};

use crate::system_audio::Output;

/// Generated by `cargo xtask sounds`.
const START: &[u8] = include_bytes!("../../../assets/sounds/start.wav");
const STOP: &[u8] = include_bytes!("../../../assets/sounds/stop.wav");

enum Request {
    Play(&'static [u8], f32),
    Duck(Duck),
    /// Acknowledged on the sender, if any, once done.
    Restore(Option<SyncSender<()>>),
}

#[derive(Clone)]
pub struct Sounds(Sender<Request>);

impl Sounds {
    pub fn start() -> Self {
        let (sender, receiver) = mpsc::channel::<Request>();
        std::thread::Builder::new()
            .name("sounds".into())
            .spawn(move || {
                let mut output = Output::new();
                let mut ducked = DuckState::default();
                for request in receiver {
                    match request {
                        Request::Play(wav, volume) => {
                            if let Err(e) = play(wav, volume) {
                                log::warn!("Playing a feedback sound failed: {e}");
                            }
                        }
                        Request::Duck(duck) => ducked.apply(duck, &mut output),
                        Request::Restore(done) => {
                            ducked.restore(&mut output);
                            // The acknowledged restore is the one at quit: nothing may duck after it.
                            if let Some(done) = done {
                                let _ = done.send(());
                                break;
                            }
                        }
                    }
                }
            })
            .expect("sounds thread");
        Self(sender)
    }

    /// The start sound (`start`) or the stop sound at the Volume setting (0 to 100).
    pub fn play(&self, start: bool, volume_percent: i32) {
        let wav = if start { START } else { STOP };
        let _ = self.0.send(Request::Play(wav, volume_percent.clamp(0, 100) as f32 / 100.0));
    }

    /// Mutes or lowers other audio; a no-op while already done.
    pub fn duck(&self, duck: Duck) {
        let _ = self.0.send(Request::Duck(duck));
    }

    /// Puts back what [`Self::duck`] changed; a no-op when nothing was.
    pub fn restore(&self) {
        let _ = self.0.send(Request::Restore(None));
    }

    /// [`Self::restore`], waiting up to 2 s for it (at quit, so the process doesn't end with the audio lowered).
    pub fn restore_blocking(&self) {
        let (done, wait) = mpsc::sync_channel(1);
        if self.0.send(Request::Restore(Some(done))).is_ok() {
            let _ = wait.recv_timeout(Duration::from_secs(2));
        }
    }
}

/// Handy `play_audio_file` on the default device: opens it, plays the sound to the end, closes it.
fn play(wav: &'static [u8], volume: f32) -> Result<(), Box<dyn std::error::Error>> {
    let mut sink = rodio::DeviceSinkBuilder::from_default_device()?.open_stream()?;
    sink.log_on_drop(false);
    let player = rodio::play(sink.mixer(), Cursor::new(wav))?;
    player.set_volume(volume);
    player.sleep_until_end();
    Ok(())
}
